export interface IconProps extends Omit<React.SVGProps<SVGSVGElement>, 'name'> {
  /** Which glyph to draw. */
  name: IconName;
  /** Edge length in pixels. Defaults to 16 — the size that sits right in buttons and table cells. */
  size?: number;
  /** Stroke weight. 1.75 is the Kōvara default; use 2 for very small sizes. */
  strokeWidth?: number;
  /** Accessible label. Omit for decorative icons — they are then hidden from assistive tech. */
  title?: string;
}

/**
 * The Kōvara line icon set — one flat 24×24 grid, `currentColor` stroke, so an icon
 * always inherits the color of the text or button it sits in.
 *
 * @example
 * <Button leadingIcon={<Icon name="sparkles" />}>Generate quote</Button>
 */
export const Icon = React.forwardRef<SVGSVGElement, IconProps>(function Icon(
  { name, size = 16, strokeWidth = 1.75, title, ...rest },
  ref
) {
  return (
    <svg
      ref={ref}
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden={title ? undefined : true}
      role={title ? 'img' : undefined}
      focusable="false"
      {...rest}
    >
      {title ? <title>{title}</title> : null}
      {PATHS[name]}
    </svg>
  );
});
